import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import type { FileKind } from './data.js';

// Node resolves this path from the backend root. The npm scripts and the Docker image run there.
const STATIC_DIR = resolve('prisma/seed/files');

const SAMPLE_TEXT = 'This is sample content generated by the database seed.';

export const MIME_TYPES: Record<FileKind, string> = {
  pdf: 'application/pdf',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  png: 'image/png',
  txt: 'text/plain',
  csv: 'text/csv',
};

const staticFiles = {
  docx: readFileSync(resolve(STATIC_DIR, 'document.docx')),
  xlsx: readFileSync(resolve(STATIC_DIR, 'spreadsheet.xlsx')),
  chart: readFileSync(resolve(STATIC_DIR, 'chart.png')),
  diagram: readFileSync(resolve(STATIC_DIR, 'diagram.png')),
};

export function buildFile(kind: FileKind, title: string, versionNumber: number): Buffer {
  const heading = `${title} (version ${versionNumber})`;
  switch (kind) {
    case 'pdf':
      return buildPdf(heading, [
        SAMPLE_TEXT,
        'Upload a new version to replace it with a real document.',
        `Generated for version ${versionNumber}.`,
      ]);
    case 'txt':
      return Buffer.from(`${heading}\n${'='.repeat(heading.length)}\n\n${SAMPLE_TEXT}\n`);
    case 'csv':
      return buildCsv(versionNumber);
    case 'png':
      if (/diagram|topology|architecture|chart/i.test(title)) {
        return staticFiles.diagram;
      }
      return staticFiles.chart;
    case 'docx':
    case 'xlsx':
      return staticFiles[kind];
  }
}

function toCsvRow(itemNumber: number, versionNumber: number): string {
  let status = 'closed';
  if (itemNumber % 2 === 1) {
    status = 'open';
  }
  const amount = itemNumber * 100 * versionNumber;
  return `Item ${itemNumber},Team ${itemNumber},${status},${amount}`;
}

function buildCsv(versionNumber: number): Buffer {
  const rows = ['item,owner,status,amount'];
  for (let itemNumber = 1; itemNumber <= 5; itemNumber++) {
    rows.push(toCsvRow(itemNumber, versionNumber));
  }
  return Buffer.from(`${rows.join('\n')}\n`);
}

function escapePdfText(text: string): string {
  return text.replace(/[\\()]/g, (char) => `\\${char}`);
}

// The first line is 40 points below the heading. Each next line is 20 points lower.
function pdfTextLine(line: string, index: number): string {
  let offset = -20;
  if (index === 0) {
    offset = -40;
  }
  return `/F1 12 Tf 0 ${offset} Td (${escapePdfText(line)}) Tj`;
}

function buildPdf(heading: string, lines: string[]): Buffer {
  const content = [
    'BT',
    `/F2 20 Tf 72 720 Td (${escapePdfText(heading)}) Tj`,
    ...lines.map(pdfTextLine),
    'ET',
  ].join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] ' +
      '/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n`;
  pdf += `startxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}
